export function detectCity(text: string): string | undefined {
  const upper = text.toUpperCase().trim();
  const sortedCities = Object.keys(INDIAN_CITIES).sort((a, b) => b.length - a.length);
  for (const variant of sortedCities) {
    if (upper.includes(variant)) {
      return INDIAN_CITIES[variant];
    }
  }
  return undefined;
}
